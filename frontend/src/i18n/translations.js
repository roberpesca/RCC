// Frontend chrome translations — Spanish is the default language, English is the
// alternative. This covers UI labels/buttons/placeholders; backend-generated content
// (program names, workout titles, coaching messages) is translated server-side via the
// `x-lang` header (see api/client.js) and arrives already in the right language.
export const SUPPORTED_LANGS = ['es', 'en'];
export const DEFAULT_LANG = 'es';
export const LANG_KEY = 'coach_lang';

export function resolveLang(value) {
  return SUPPORTED_LANGS.includes(value) ? value : DEFAULT_LANG;
}

export function getStoredLang() {
  try {
    return resolveLang(localStorage.getItem(LANG_KEY));
  } catch {
    return DEFAULT_LANG;
  }
}

export function setStoredLang(lang) {
  try {
    localStorage.setItem(LANG_KEY, resolveLang(lang));
  } catch {
    // ignore (e.g. storage disabled)
  }
}

